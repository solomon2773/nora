#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DEFAULT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const AUTH_TYPES = new Set(["api_key"]);

export function toCamelCase(value) {
  return String(value)
    .split(/[-_]/g)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part.toLowerCase() : part[0].toUpperCase() + part.slice(1).toLowerCase(),
    )
    .join("");
}

function assertOption(condition, message) {
  if (!condition) throw new Error(message);
}

function appendCatalogEntry(source, entry) {
  const closingMatch = source.match(/\]\s*$/);
  const closingIndex = closingMatch?.index ?? -1;
  assertOption(closingIndex >= 0, "catalog.json must end with a JSON array");
  const before = source.slice(0, closingIndex).trimEnd();
  const separator = before.endsWith("[") ? "\n" : ",\n";
  const formatted = JSON.stringify(entry, null, 2)
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
  return `${before}${separator}${formatted}\n]\n`;
}

function insertBefore(source, anchor, addition, label) {
  const index = source.indexOf(anchor);
  assertOption(index >= 0, `Could not find ${label} insertion point`);
  return `${source.slice(0, index)}${addition}${source.slice(index)}`;
}

function findNavigationGroup(groups, label) {
  for (const group of Array.isArray(groups) ? groups : []) {
    if (group?.group === label && Array.isArray(group.pages)) return group;
    const nested = findNavigationGroup(
      (group?.pages || []).filter((page) => page && typeof page === "object"),
      label,
    );
    if (nested) return nested;
  }
  return null;
}

function addDocsNavigationPage(source, page) {
  const config = JSON.parse(source);
  const group = findNavigationGroup(config?.navigation?.groups, "Per-provider integrations");
  assertOption(group, "Could not find Per-provider integrations in docs/docs.json");
  assertOption(!group.pages.includes(page), `${page} is already present in docs navigation`);
  const indexPage = group.pages.includes("guides/integrations/index")
    ? ["guides/integrations/index"]
    : [];
  const providerPages = group.pages
    .filter((entry) => typeof entry === "string" && entry !== "guides/integrations/index")
    .concat(page)
    .sort((left, right) => left.localeCompare(right));
  group.pages = [...indexPage, ...providerPages];
  return `${JSON.stringify(config, null, 2)}\n`;
}

async function formatWrites(writes) {
  let prettier;
  try {
    prettier = await import("prettier");
  } catch {
    throw new Error(
      "Prettier is required to generate repository-ready files. Run npm run contributor:setup -- --scope root first.",
    );
  }
  const formatted = new Map();
  for (const [file, contents] of writes) {
    const nextContents = /\.(?:ts|json|mdx)$/.test(file)
      ? await prettier.format(contents, { filepath: file, printWidth: 100 })
      : contents;
    formatted.set(file, nextContents);
  }
  return formatted;
}

function providerSource({ id, name, variable, primaryEnv, testUrl }) {
  return `// ${name} provider — generated by npm run scaffold:integration.
// Replace the generic bearer request/message when this API uses a different convention.

import type {
  ConnectivityResult,
  DecryptedIntegration,
  EnvMapping,
  Provider,
  ProviderDeps,
} from "../types/provider";

export const ${variable}Provider: Provider = {
  id: ${JSON.stringify(id)},
  authType: "api_key",

  async test(
    ctx: DecryptedIntegration,
    deps: ProviderDeps,
  ): Promise<ConnectivityResult> {
    try {
      const response = await deps.fetch(${JSON.stringify(testUrl)}, {
        headers: { Authorization: \`Bearer \${ctx.token ?? ""}\` },
      });
      if (!response.ok) {
        throw new Error(${JSON.stringify(name)} + \` API returned \${response.status}\`);
      }
      return { success: true, message: ${JSON.stringify(`${name} credentials verified`)} };
    } catch (error: any) {
      return { success: false, error: error?.message ?? String(error) };
    }
  },

  mapToEnv(_ctx: DecryptedIntegration): EnvMapping {
    return { primary: ${JSON.stringify(primaryEnv)}, config: {} };
  },
};
`;
}

function testSource({ id, name, fileStem, variable, primaryEnv, testUrl }) {
  return `// @ts-nocheck
const { ${variable}Provider } = require("../../integrations/providers/${fileStem}");

function makeDeps(fetchImpl) {
  return {
    fetch: fetchImpl,
    assertSafeUrl: async (url) => url,
    encrypt: (value) => value,
    decrypt: (value) => value,
    ensureEncryptionConfigured: jest.fn(),
    db: { query: jest.fn() },
  };
}

describe(${JSON.stringify(`${variable}Provider`)}, () => {
  it("declares its catalog identity", () => {
    expect(${variable}Provider.id).toBe(${JSON.stringify(id)});
    expect(${variable}Provider.authType).toBe("api_key");
  });

  it("verifies credentials with the provider API", async () => {
    const fetchImpl = jest.fn().mockResolvedValue({ ok: true, status: 200 });
    const result = await ${variable}Provider.test(
      { row: { provider: ${JSON.stringify(id)} }, token: "test-token", config: {} },
      makeDeps(fetchImpl),
    );

    expect(fetchImpl).toHaveBeenCalledWith(
      ${JSON.stringify(testUrl)},
      expect.objectContaining({
        headers: expect.objectContaining({
          Authorization: "Bearer test-token",
        }),
      }),
    );
    expect(result).toEqual({
      success: true,
      message: ${JSON.stringify(`${name} credentials verified`)},
    });
  });

  it("returns a useful failure for a rejected credential", async () => {
    const result = await ${variable}Provider.test(
      { row: { provider: ${JSON.stringify(id)} }, token: "bad-token", config: {} },
      makeDeps(jest.fn().mockResolvedValue({ ok: false, status: 401 })),
    );

    expect(result.success).toBe(false);
    expect(result.error).toContain(${JSON.stringify(`${name} API returned 401`)});
  });

  it("maps the primary credential into the runtime environment", () => {
    expect(
      ${variable}Provider.mapToEnv({
        row: { provider: ${JSON.stringify(id)} },
        token: null,
        config: {},
      }),
    ).toEqual({ primary: ${JSON.stringify(primaryEnv)}, config: {} });
  });
});
`;
}

function docsSource({ name, primaryEnv, testUrl, credentialsUrl }) {
  const credentialLink = credentialsUrl
    ? `Create the narrowest practical credential at ${credentialsUrl}.`
    : "Document the provider's official credential-creation URL here.";
  return `# ${name}

> Connect ${name} credentials to Nora-managed agents.

## Create credentials

${credentialLink}

Use a dedicated, least-privilege credential and rotate it according to your organization's policy.

## Connect in Nora

Add ${name} from the Integrations page and paste the credential. Nora verifies it against \`${testUrl}\` before syncing it to selected runtimes.

## Environment variable Nora injects

- \`${primaryEnv}\` — API key field

## Contributor notes

Replace this generated baseline with provider-specific scopes, setup steps, failure modes, and tool/MCP guidance before opening a pull request.
`;
}

export async function scaffoldIntegration(options) {
  const root = path.resolve(options.root || DEFAULT_ROOT);
  const id = String(options.id || "").trim();
  const name = String(options.name || "").trim();
  const authType = String(options.authType || "api_key").trim();
  const primaryEnv = String(options.primaryEnv || "").trim();
  const testUrl = String(options.testUrl || "").trim();
  const category = String(options.category || "developer-tools").trim();
  const description = String(
    options.description || `Connect ${name} to Nora-managed agents`,
  ).trim();
  const credentialKey = String(options.credentialKey || "api_key").trim();
  const credentialLabel = String(options.credentialLabel || "API Key").trim();
  const credentialsUrl = String(options.credentialsUrl || "").trim();

  assertOption(/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(id), "--id must be kebab-case");
  assertOption(name.length > 0, "--name is required");
  assertOption(
    AUTH_TYPES.has(authType),
    "The public generator currently supports --auth api_key only",
  );
  assertOption(/^[A-Z][A-Z0-9_]*$/.test(primaryEnv), "--primary-env must be an uppercase env name");
  assertOption(/^[a-z][a-z0-9_]*$/.test(credentialKey), "--credential-key must be snake_case");
  assertOption(category.length > 0, "--category cannot be empty");

  let parsedUrl;
  try {
    parsedUrl = new URL(testUrl);
  } catch {
    throw new Error("--test-url must be an absolute HTTPS URL");
  }
  assertOption(parsedUrl.protocol === "https:", "--test-url must use HTTPS");
  if (credentialsUrl) {
    let parsedCredentialsUrl;
    try {
      parsedCredentialsUrl = new URL(credentialsUrl);
    } catch {
      throw new Error("--credentials-url must be an absolute HTTPS URL");
    }
    assertOption(parsedCredentialsUrl.protocol === "https:", "--credentials-url must use HTTPS");
  }

  const fileStem = toCamelCase(id);
  const variable = fileStem;
  const paths = {
    provider: path.join(root, "backend-api", "integrations", "providers", `${fileStem}.ts`),
    test: path.join(root, "backend-api", "__tests__", "providers", `${fileStem}Provider.test.ts`),
    catalog: path.join(root, "backend-api", "integrations", "catalog", "catalog.json"),
    service: path.join(root, "backend-api", "integrations", "services", "integrationsService.ts"),
    docs: path.join(root, "docs", "guides", "integrations", `${id}.mdx`),
    docsNavigation: path.join(root, "docs", "docs.json"),
    smokeEnv: path.join(root, "e2e", "integrations", ".env.providers.example"),
  };

  for (const file of [paths.provider, paths.test, paths.docs]) {
    assertOption(
      !fs.existsSync(file),
      `Refusing to overwrite existing file: ${path.relative(root, file)}`,
    );
  }

  const catalogSource = fs.readFileSync(paths.catalog, "utf8");
  const catalog = JSON.parse(catalogSource);
  assertOption(Array.isArray(catalog), "catalog.json must contain an array");
  assertOption(!catalog.some((item) => item.id === id), `Catalog provider ${id} already exists`);
  const knownCategories = new Set(catalog.map((item) => item.category).filter(Boolean));
  if (knownCategories.size > 0) {
    assertOption(
      knownCategories.has(category),
      `--category must be one of: ${[...knownCategories].sort().join(", ")}`,
    );
  }

  let serviceSource = fs.readFileSync(paths.service, "utf8");
  const providerVariable = `${variable}Provider`;
  assertOption(
    !serviceSource.includes(providerVariable),
    `${providerVariable} is already registered`,
  );
  serviceSource = insertBefore(
    serviceSource,
    "const repo = createIntegrationsRepository(db);",
    `const { ${providerVariable} } = require("../providers/${fileStem}");\n`,
    "provider import",
  );
  const registrationAnchor = "].forEach((p) => providerRegistry.register(p));";
  const registryStart = serviceSource.indexOf("const providerRegistry =");
  const registrationIndex = serviceSource.indexOf(registrationAnchor, registryStart);
  assertOption(
    registryStart >= 0 && registrationIndex >= 0,
    "Could not find provider registry array",
  );
  serviceSource = `${serviceSource.slice(0, registrationIndex)}  ${providerVariable},\n${serviceSource.slice(registrationIndex)}`;

  const catalogEntry = {
    id,
    name,
    icon: "plug",
    category,
    description,
    authType,
    configFields: [
      {
        key: credentialKey,
        label: credentialLabel,
        type: "password",
        required: true,
      },
    ],
    capabilities: ["read"],
    ...(credentialsUrl ? { credentialsUrl } : {}),
    setupGuide: {
      steps: [
        `Create a dedicated, least-privilege ${name} credential.`,
        "Paste the credential into Nora and run the connection test.",
      ],
    },
    mcp: { available: false },
  };

  const writes = new Map([
    [paths.provider, providerSource({ id, name, variable, primaryEnv, testUrl })],
    [paths.test, testSource({ id, name, fileStem, variable, primaryEnv, testUrl })],
    [paths.catalog, appendCatalogEntry(catalogSource, catalogEntry)],
    [paths.service, serviceSource],
    [paths.docs, docsSource({ name, primaryEnv, testUrl, credentialsUrl })],
    [
      paths.docsNavigation,
      addDocsNavigationPage(
        fs.readFileSync(paths.docsNavigation, "utf8"),
        `guides/integrations/${id}`,
      ),
    ],
  ]);

  const smokeSource = fs.readFileSync(paths.smokeEnv, "utf8");
  if (!new RegExp(`^${primaryEnv}=`, "m").test(smokeSource)) {
    writes.set(paths.smokeEnv, `${smokeSource.trimEnd()}\n\n# ${name}\n${primaryEnv}=\n`);
  }

  const formattedWrites = await formatWrites(writes);

  if (!options.dryRun) {
    for (const [file, contents] of formattedWrites) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, contents, "utf8");
    }
  }

  return {
    dryRun: Boolean(options.dryRun),
    files: [...formattedWrites.keys()].map((file) => path.relative(root, file)),
    nextSteps: [
      "Replace the generated bearer check with the provider's exact auth and error semantics.",
      "Add config fields/env mappings and tool specs only when they are implemented and tested.",
      `Run npm run contributor:check -- integrations.`,
    ],
  };
}

function parseArgs(argv) {
  const options = {};
  const valueOptions = new Map([
    ["--id", "id"],
    ["--name", "name"],
    ["--auth", "authType"],
    ["--primary-env", "primaryEnv"],
    ["--test-url", "testUrl"],
    ["--category", "category"],
    ["--description", "description"],
    ["--credential-key", "credentialKey"],
    ["--credential-label", "credentialLabel"],
    ["--credentials-url", "credentialsUrl"],
  ]);
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--dry-run") options.dryRun = true;
    else if (arg === "--help" || arg === "-h") options.help = true;
    else if (valueOptions.has(arg)) {
      const value = argv[index + 1];
      assertOption(value && !value.startsWith("--"), `${arg} requires a value`);
      options[valueOptions.get(arg)] = value;
      index += 1;
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }
  return options;
}

function printHelp() {
  process.stdout.write(`Usage:
  npm run scaffold:integration -- --id acme --name "Acme" \\
    --primary-env ACME_API_KEY --test-url https://api.acme.example/v1/me

Options:
  --auth api_key              Supported generated auth baseline (default: api_key)
  --category <catalog-group>  Catalog category (default: developer-tools)
  --description <text>        Catalog description
  --credential-key <key>      Catalog field key (default: api_key)
  --credential-label <label>  Catalog field label (default: API Key)
  --credentials-url <https>   Official credential creation page
  --dry-run                   Validate and list files without writing
`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    const options = parseArgs(process.argv.slice(2));
    if (options.help) printHelp();
    else {
      const result = await scaffoldIntegration(options);
      process.stdout.write(
        `${result.dryRun ? "Would create/update" : "Created/updated"}:\n${result.files.map((file) => `  - ${file}`).join("\n")}\n\nNext steps:\n${result.nextSteps.map((step) => `  - ${step}`).join("\n")}\n`,
      );
    }
  } catch (error) {
    process.stderr.write(`Integration scaffold failed: ${error.message}\n`);
    process.exitCode = 1;
  }
}
